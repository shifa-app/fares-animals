// تُروى بصوت عربي بطيء واضح، مع نص قصير وصورة بسيطة لكل قصة.
// القصص الطويلة (5 دقائق): مقسمة إلى مشاهد قصيرة متتالية،
// وكل مشهد له أيقونة معبرة (مفتاح نصي يُترجم لأيقونة في الشاشة).

/// مشهد واحد من قصة طويلة. قد يحتوي نصه على {name} الذي
/// يُستبدل باسم الطفل النشط في القصص المخصصة.
class BedtimeStoryScene {
  final String text;
  final String icon;
  const BedtimeStoryScene({required this.text, required this.icon});
}

class BedtimeStory {
  final String title, emoji, body, moral;
  final bool isProphet;

  /// قصة مخصصة: {name} في العنوان والمشاهد يُستبدل باسم الطفل النشط.
  final bool personalized;

  /// القيمة التربوية للقصة الطويلة (مثلاً: الصدق، الشجاعة).
  final String? value;

  /// مشاهد القصة الطويلة؛ فارغة في القصص القصيرة الكلاسيكية.
  final List<BedtimeStoryScene> scenes;

  const BedtimeStory({
    required this.title,
    required this.emoji,
    required this.body,
    required this.moral,
    this.isProphet = false,
    this.personalized = false,
    this.value,
    this.scenes = const [],
  });

  /// قصة طويلة (5 دقائق) بمشاهد متتالية.
  bool get isFiveMinute => scenes.isNotEmpty;

  String titleFor(String child) =>
      personalized ? title.replaceAll('{name}', child) : title;

  String sceneTextFor(int index, String child) {
    final t = scenes[index].text;
    return personalized ? t.replaceAll('{name}', child) : t;
  }

  /// عدد كلمات القصة (المشاهد في الطويلة، والنص في القصيرة).
  int get wordCount {
    final text = isFiveMinute
        ? scenes.map((s) => s.text).join(' ')
        : body;
    return text
        .split(RegExp(r'\s+'))
        .where((w) => w.trim().isNotEmpty)
        .length;
  }
}

